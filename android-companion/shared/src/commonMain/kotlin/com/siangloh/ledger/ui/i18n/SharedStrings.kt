    fun format1(template: String, arg1: Any): String =
        replaceNextPlaceholder(template, arg1.toString())

    fun format2(template: String, arg1: Any, arg2: Any): String =
        replaceNextPlaceholder(replaceNextPlaceholder(template, arg1.toString()), arg2.toString())

    fun format3(template: String, arg1: Any, arg2: Any, arg3: Any): String =
        replaceNextPlaceholder(
            replaceNextPlaceholder(
                replaceNextPlaceholder(template, arg1.toString()),
                arg2.toString()
            ),
            arg3.toString()
        )

    private fun replaceNextPlaceholder(source: String, replacement: String): String {
        val idxS = source.indexOf("%s")
        val idxD = source.indexOf("%d")
        val idx = when {
            idxS >= 0 && idxD >= 0 -> minOf(idxS, idxD)
            idxS >= 0 -> idxS
            else -> idxD
        }
        if (idx < 0) return source
        return source.substring(0, idx) + replacement + source.substring(idx + 2)
    }
